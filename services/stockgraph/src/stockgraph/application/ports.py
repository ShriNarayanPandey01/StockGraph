"""Application-owned contracts for graph processing and evidence reads."""

from typing import Any, Protocol

from pydantic import BaseModel
from stockgraph.domain.events import CommittedEvent
from stockgraph.domain.schemas import StockContextCard


class GraphEventHandler(Protocol):
    def handle(self, event: CommittedEvent) -> None: ...


class GraphEventProcessor(Protocol):
    def process(self, event: CommittedEvent) -> None: ...


class ChatModel(Protocol):
    def complete_json(self, prompt: str, schema: type[BaseModel], **kwargs: Any) -> BaseModel: ...


class EmbeddingModel(Protocol):
    def embed_one(self, text: str) -> list[float]: ...


class StockProfileReader(Protocol):
    def get_entity(self, kind: str, entity_id: str) -> dict | None: ...
    def get_active_exposures(self, ticker: str) -> list[str]: ...


class GuidanceReader(Protocol):
    def guidance_highlights(self, ticker: str) -> list[str]: ...


class StockContextBuilder(Protocol):
    def build_context_card(self, ticker: str) -> StockContextCard: ...


class ProfessionalEvidenceReader(Protocol):
    def professional_page(self, ticker: str, start: int, end: int,
                          offset: int = 0, limit: int = 50) -> list[dict]: ...


class EvidenceWriter(Protocol):
    def project_author_status(self, event: Any) -> bool: ...
    def project_document(self, event: Any) -> Any: ...
    def embed_document_chunk(self, chunk_id: str, embedding: list[float]) -> Any: ...
    def document_semantic_status(self, version_id: str, status: str) -> Any: ...
    def project_professional(self, event: Any, payload: Any) -> bool: ...


class GraphContextReader(Protocol):
    def get_entity(self, kind: str, entity_id: str) -> dict | None: ...
    def context_page(self, ticker: str, start: int, end: int,
                     offset: int = 0, limit: int = 50) -> dict: ...
    def exploration_neighbors(self, frontier: list[str], start: int, end: int,
                              limit: int) -> list: ...


class NewsImpactWriter(Protocol):
    def reconcile_news_impacts(self, news_id: str, scope_tickers: list[str],
                               stock_impacts: list[dict], market_impacts: list[dict]) -> None: ...


class RegistryStore(StockProfileReader, Protocol):
    def catalog(self) -> dict[str, list[dict]]: ...
    def project_entity(self, kind: str, entity_id: str, entity: dict,
                       revision: int, event_ts: int) -> Any: ...
    def merge_stock_profile_embedding(self, ticker: str, embedding: list[float]) -> Any: ...
    def rotate_dynamic_ontology_edges(self, ticker: str, edges: list, new_ts: int) -> Any: ...
    def merge_ontology_edge(self, **kwargs: Any) -> Any: ...
    def historical_news(self, start_ts: int, offset: int = 0, limit: int = 100) -> list[dict]: ...
    def mark_entity_processed(self, kind: str, entity_id: str, revision: int) -> Any: ...


class NewsStore(StockProfileReader, NewsImpactWriter, Protocol):
    def catalog(self) -> dict[str, list[dict]]: ...
    def find_news(self, news_id: str) -> dict | None: ...
    def find_text_dup(self, *args: Any) -> Any: ...
    def find_near_dup(self, *args: Any) -> Any: ...
    def merge_news_event(self, props: dict, embedding: list[float] | None = None) -> Any: ...
    def link_duplicate(self, dup_id: str, canon_id: str) -> Any: ...
    def find_correlation_candidates(self, *args: Any, **kwargs: Any) -> list: ...
    def merge_news_correlation(self, *args: Any) -> Any: ...


class GraphWriteControl(Protocol):
    def set_write_guard(self, guard: Any | None) -> None: ...
    def mark_entity_failed(self, kind: str, entity_id: str) -> None: ...


class GraphProcessingStore(RegistryStore, NewsStore, GraphWriteControl, Protocol):
    pass


class EventStateStore(Protocol):
    def get(self, key: str) -> Any: ...
    def set(self, key: str, value: str, **kwargs: Any) -> Any: ...
    def hget(self, key: str, field: str) -> Any: ...
    def hset(self, key: str, *, mapping: dict) -> Any: ...


class NewsRoutingHandler(GraphEventHandler, Protocol):
    def route(self, news: dict, resolver: Any, chat: ChatModel,
              only_tickers: list[str] | None = None, sentiment_by_ticker: Any = None,
              article_sentiment: float | None = None) -> None: ...
