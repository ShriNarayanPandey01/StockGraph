"""Interfaces owned by the Data Service's application workflows."""

from datetime import date, datetime
from typing import Any, Protocol

from upstox_service.domain.entities import NewsArticle
from upstox_service.domain.models import CompanyBundle, StockRegistration
from upstox_service.domain.news import ProviderFetchResult, StagedNewsItem


class RegistrationJobPort(Protocol):
    async def create_job(self, request: StockRegistration) -> dict: ...
    async def claim_job(self, lease_seconds: int, max_attempts: int) -> dict | None: ...
    async def renew_job(self, job_id: str, attempt: int, lease_seconds: int) -> bool: ...
    async def commit_company(self, job_id: str, bundle: CompanyBundle, *, attempt: int) -> None: ...
    async def fail_job(self, job_id: str, error: str, retry: bool, *, attempt: int) -> None: ...


class CompanyProviderPort(Protocol):
    async def fetch_company(self, request: StockRegistration) -> CompanyBundle: ...


class StockDataRepositoryPort(Protocol):
    async def refresh_universe(self, instruments: list[dict]) -> dict[str, int]: ...
    async def search_instruments(
        self, query: str, exchange: str | None, after: tuple | None, limit: int
    ) -> list[dict]: ...
    async def get_instrument(self, ticker: str, exchange: str) -> dict | None: ...
    async def upsert_instrument(self, row: dict) -> None: ...
    async def is_registered(self, ticker: str, isin: str) -> bool: ...
    async def get_profile(self, isin: str) -> dict | None: ...
    async def save_profile(self, isin: str, profile: dict, as_of: datetime) -> None: ...
    async def get_shareholding(self, isin: str) -> dict: ...
    async def save_shareholding(self, isin: str, rows: list[dict], as_of: datetime) -> None: ...
    async def has_candle_coverage(
        self, exchange: str, isin: str, start: date, end: date
    ) -> bool: ...
    async def save_candles(
        self, exchange: str, isin: str, start: date, end: date, rows: list[dict], as_of: datetime
    ) -> None: ...
    async def get_candles(self, exchange: str, isin: str, start: date, end: date) -> list[dict]: ...


class StockDataProviderPort(Protocol):
    async def resolve(self, ticker: str, exchange: str) -> dict: ...
    async def fetch_profile(self, isin: str) -> dict: ...
    async def fetch_shareholding(self, isin: str) -> list[dict]: ...
    async def fetch_daily_candles(
        self, instrument_key: str, start: date, end: date
    ) -> list[dict]: ...
    async def fetch_equity_universe(self) -> list[dict]: ...


class NewsProviderPort(Protocol):
    provider_id: str
    priority: int
    plan_daily_cap: int

    @property
    def is_configured(self) -> bool: ...
    def fetch(self, since: datetime, limit: int) -> ProviderFetchResult: ...
    def normalize_staged(self, payload: dict) -> list[tuple[NewsArticle, StagedNewsItem]]: ...


class RequestQuotaPort(Protocol):
    def try_consume(self, provider_id: str, provider_cap: int) -> bool: ...
    def consumed(self, provider_id: str) -> int: ...


class NewsCommitPort(Protocol):
    async def commit_news(self, result: ProviderFetchResult) -> int: ...


class NewsPersistencePort(Protocol):
    async def stage(self, result: ProviderFetchResult) -> None: ...
    async def advance(self, provider_id: str, result: ProviderFetchResult) -> None: ...


class ManualNewsStorePort(NewsCommitPort, Protocol):
    async def get_entity(self, kind: str, entity_id: str) -> dict | None: ...


class NewsStagingPort(Protocol):
    async def get_news_watermark(self, provider_id: str) -> datetime | None: ...
    async def get_staged_news(self, limit: int = 500) -> list[dict]: ...
    async def stage_news_raw(self, **kwargs: Any) -> Any: ...
    async def advance_news_watermark(self, provider_id: str, published_at: datetime) -> None: ...
    async def defer_news_review(self, provider_id: str, external_id: str) -> None: ...


class PendingNewsReviewPort(Protocol):
    async def pending_news_reviews(self, limit: int = 100) -> list[dict]: ...
    async def defer_news_review(self, provider_id: str, external_id: str) -> None: ...
    async def finish_news_review(self, provider_id: str, external_id: str) -> None: ...


class NewsReviewStorePort(NewsCommitPort, PendingNewsReviewPort, Protocol):
    pass


class CheckpointRepositoryPort(Protocol):
    async def list_catalog(self, kind: str) -> list[dict]: ...
    async def get_watermark(self, vendor_id: str, ticker: str, series: str) -> date | None: ...
    async def missing_checkpoint_dates(
        self, ticker: str, session: str, start: date, end: date
    ) -> list[date]: ...
    async def stage_vendor_quote(
        self,
        vendor_id: str,
        ticker: str,
        trade_date: date,
        series: str,
        payload: Any,
        fetched_at: datetime,
    ) -> Any: ...
    async def upsert_daily_metrics(self, rows: list[dict]) -> int: ...
    async def advance_watermark(
        self, vendor_id: str, ticker: str, series: str, trade_date: date
    ) -> None: ...


class PriceCheckpointProviderPort(Protocol):
    async def fetch_checkpoint(
        self, instrument_key: str, trade_date: date, session: str, today: date
    ) -> tuple[dict | None, Any]: ...


class BhavcopyProviderPort(Protocol):
    async def fetch(self, trade_date: date) -> dict[str, dict]: ...
