"""Structural ports for Platform use cases.

Implementations live in the Platform adapters. These protocols deliberately
describe business operations instead of exposing an asyncpg pool or HTTPX
client to the application layer.
"""

from __future__ import annotations

from datetime import date
from typing import Any, Protocol
from uuid import UUID

from pydantic import SecretStr

from marketgraph_platform.models import ContributionInput, Principal


class AccountRepositoryPort(Protocol):
    async def authenticate(self, digest: str) -> dict[str, Any] | None: ...
    async def allow_request(self, user_id: UUID) -> bool: ...
    async def count_auth_attempt(self, key: str, limit: int) -> None: ...
    async def create_account(self, email: str, name: str, password_hash: str) -> None: ...
    async def login_candidate(self, email: str) -> Any: ...
    async def create_login_session(self, user_id: UUID, expected_hash: str, digest: str,
                                   ttl_seconds: int, replacement_hash: str | None = None) -> Any: ...
    async def revoke_session(self, digest: str) -> None: ...
    async def account_password_hash(self, user_id: UUID) -> str | None: ...
    async def change_account_password(self, user_id: UUID, expected_hash: str,
                                      replacement_hash: str) -> None: ...
    async def list_account_rows(self, limit: int, offset: int) -> list[Any]: ...
    async def account_row(self, user_id: UUID) -> Any: ...
    async def update_account(self, actor: Principal, user_id: UUID, changes: dict[str, Any]) -> Any: ...
    async def revoke_account_sessions(self, actor: Principal, user_id: UUID) -> dict[str, str]: ...
    async def synchronize_developer(self, name: str, email: str, password: str,
                                    verify_password: Any, hash_password: Any) -> None: ...
    async def measure(self, user_id: UUID, feature: str, units: int = 1) -> None: ...
    async def audit_action(self, actor_id: UUID, action: str,
                           target_id: UUID | None = None, details: dict[str, Any] | None = None) -> None: ...


class AccessRepositoryPort(Protocol):
    async def load_access_snapshot(self, user_id: UUID) -> Any: ...
    async def replace_active_stocks(self, user_id: UUID, tickers: tuple[str, ...]) -> None: ...
    async def usage_summary(self, user_id: UUID) -> dict[str, Any]: ...
    async def usage(self, user_id: UUID) -> list[dict[str, Any]]: ...


class BrokerRepositoryPort(Protocol):
    async def broker_status(self, user_id: UUID) -> dict[str, Any]: ...
    async def save_broker_credential(self, user_id: UUID, encrypted: bytes) -> dict[str, Any]: ...
    async def read_broker_credential(self, user_id: UUID) -> dict[str, Any] | None: ...
    async def disconnect_broker(self, user_id: UUID) -> dict[str, Any]: ...
    async def require_broker_reconnect(self, user_id: UUID, revision: int) -> None: ...


class ContributionRepositoryPort(Protocol):
    async def measure(self, user_id: UUID, feature: str, units: int = 1) -> None: ...
    async def create_contribution(self, user: Principal, data: ContributionInput,
                                  request_key: str | None = None) -> dict[str, Any]: ...
    async def add_version(self, contribution_id: UUID, user: Principal,
                          data: ContributionInput, expected_revision: int) -> dict[str, Any]: ...
    async def submit(self, contribution_id: UUID, user: Principal,
                     expected_revision: int) -> dict[str, Any]: ...
    async def review(self, contribution_id: UUID, user: Principal, expected_revision: int,
                     decision: str, reason: str) -> dict[str, Any]: ...
    async def retract(self, contribution_id: UUID, user: Principal, expected_revision: int,
                      reason: str) -> dict[str, Any]: ...


class DataClientPort(Protocol):
    async def get(self, path: str, params: dict[str, Any] | None = None, *,
                  headers: dict[str, str] | None = None) -> Any: ...
    async def post_internal(self, path: str, payload: dict[str, Any], *,
                            headers: dict[str, str] | None = None) -> Any: ...
    async def patch_internal(self, path: str, payload: dict[str, Any], *,
                             headers: dict[str, str] | None = None) -> Any: ...
    async def validate_ticker(self, ticker: str) -> str: ...
    async def validate_citations(self, content: ContributionInput) -> None: ...


class GraphClientPort(Protocol):
    async def get(self, path: str, params: dict[str, Any] | None = None, *,
                  professional: bool = False, developer: bool = False) -> Any: ...
    async def request(self, method: str, path: str, *, body: Any = None,
                      params: dict[str, Any] | None = None,
                      professional: bool = False, developer: bool = False) -> Any: ...


class JobRepositoryPort(Protocol):
    async def create_research_job(self, owner_id: UUID, kind: str, payload: dict[str, Any],
                                  key: str, max_pending: int,
                                  actor_id: UUID | None = None) -> dict[str, Any]: ...
    async def reserve_tool_call(self, job_id: UUID, lease: UUID, actor: str) -> Any: ...
    async def register_evidence(self, job_id: UUID, lease: UUID,
                                entries: list[dict[str, Any]]) -> Any: ...
    async def conversation_owner(self, conversation_id: UUID, user: Principal) -> UUID: ...


class EvidenceRepositoryPort(Protocol):
    async def published(self, ticker: str, limit: int = 50,
                        offset: int = 0) -> list[dict[str, Any]]: ...
    async def current_professional_evidence(self, version_id: UUID) -> bool: ...


class CredentialVaultPort(Protocol):
    def encrypt(self, owner_id: UUID, token: SecretStr) -> bytes: ...
    def decrypt(self, owner_id: UUID, ciphertext: bytes) -> SecretStr: ...


class AuditRepositoryPort(Protocol):
    async def audit(self, actor_id: UUID, action: str, target_id: UUID | None = None,
                    details: dict[str, Any] | None = None) -> None: ...


class ClockPort(Protocol):
    def today(self) -> date: ...
